def _tbl(rows, cols, headers=None):
    headers = headers or cols
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(cols)) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(r.get(c, "")) for c in cols) + " |")
    return "\n".join(out)


PACE_PBP_COUNTS = Path("data/processed/possessions_pbp.parquet")
POSS_DIR = Path("data/processed/possessions")


def _cross_source_table(
    pace_counts: Path = PACE_PBP_COUNTS, poss_dir: Path = POSS_DIR
) -> str | None:
    """Per-game agreement between this build's CBBD possession count and the L2
    pace worker's independent hoopR count, on the games both cover.

    Returns None (and the section is simply omitted) if the pace worker's
    artifact is not present -- this build must not depend on another worker's
    file existing, only benefit from it when it does. Nothing here writes to
    that file."""
    try:
        import pandas as pd

        if not Path(pace_counts).exists():
            return None
        tp = pd.read_parquet(pace_counts, columns=["game_id", "season", "poss_pbp"])
        rows = []
        for season in sorted(tp["season"].unique()):
            p = Path(poss_dir) / f"possessions_{int(season)}.parquet"
            if not p.exists():
                continue
            d = pd.read_parquet(p, columns=["game_id"])
            mine = d.groupby("game_id").size().div(2).rename("poss_cbbd").reset_index()
            m = mine.merge(tp[tp["season"] == season][["game_id", "poss_pbp"]], on="game_id", how="inner")
            if not len(m):
                continue
            diff = m["poss_cbbd"] - m["poss_pbp"]
            rows.append({
                "Season": int(season), "games both cover": len(m),
                "this build (CBBD)": round(float(m["poss_cbbd"].mean()), 3),
                "pace worker (hoopR)": round(float(m["poss_pbp"].mean()), 3),
                "mean diff": f'{float(diff.mean()):+.3f}',
                "SD of diff": round(float(diff.std()), 3),
                "corr": round(float(m["poss_cbbd"].corr(m["poss_pbp"])), 4),
            })
        if not rows:
            return None
        return _tbl(rows, ["Season", "games both cover", "this build (CBBD)", "pace worker (hoopR)",
                           "mean diff", "SD of diff", "corr"])
    except Exception:
        return None


